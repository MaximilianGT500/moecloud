export function emojiFor(title: string): string | null {
  const lower = title.toLowerCase();
  for (const [pattern, emoji] of RULES) if (pattern.test(lower)) return emoji;
  return null;
}

export const startsWithEmoji = (title: string) => /^\p{Extended_Pictographic}/u.test(title.trim());
